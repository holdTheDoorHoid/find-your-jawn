// Writes src/engine/centroids.ts: the middle of each Philadelphia neighborhood, planning district
// and ZIP code, as latitude and longitude rounded to four places (about 10 meters).
//
// The matching engine uses these to estimate travel time from where a visitor says they start
// (a neighborhood or a ZIP) to a group. No geolocation, no network at run time.
//
// Inputs are the boundary files the vocabulary agent downloaded into $FYJ_CACHE/vocab/ (City of
// Philadelphia and OpenDataPhilly, both open data). Run with `node scripts/make-centroids.mjs` only
// when the vocabulary's neighborhood list changes. The output is committed, so builds never need
// the cache.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const cache = process.env.FYJ_CACHE ?? path.join(os.homedir(), '.cache', 'find-your-jawn');
const vocabDir = path.resolve(here, '../../data/vocab');
const outFile = path.resolve(here, '../src/engine/centroids.ts');

function readGeo(name) {
  return JSON.parse(fs.readFileSync(path.join(cache, 'vocab', `${name}.geojson`), 'utf8'));
}

function slug(s) {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

// Area weighted centroid of the outer rings, on a flat map around Philadelphia's latitude.
const KX = Math.cos((40 * Math.PI) / 180);

function ringCentroid(ring) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x1, y1] = [ring[i][0] * KX, ring[i][1]];
    const [x2, y2] = [ring[i + 1][0] * KX, ring[i + 1][1]];
    const f = x1 * y2 - x2 * y1;
    a += f;
    cx += (x1 + x2) * f;
    cy += (y1 + y2) * f;
  }
  a /= 2;
  if (a === 0) return null;
  return { area: Math.abs(a), x: cx / (6 * a) / KX, y: cy / (6 * a) };
}

function featureCentroid(geometry) {
  const polys = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  let total = 0;
  let x = 0;
  let y = 0;
  for (const poly of polys) {
    const c = ringCentroid(poly[0]);
    if (!c) continue;
    total += c.area;
    x += c.x * c.area;
    y += c.y * c.area;
  }
  if (total === 0) throw new Error('empty geometry');
  return [Math.round((y / total) * 1e4) / 1e4, Math.round((x / total) * 1e4) / 1e4];
}

const hoods = parseYaml(fs.readFileSync(path.join(vocabDir, 'neighborhoods.yaml'), 'utf8'));

const hoodGeo = new Map();
for (const f of readGeo('neighborhoods').features) {
  for (const key of [f.properties.NAME, f.properties.LISTNAME, f.properties.MAPNAME]) {
    if (key) hoodGeo.set(slug(key), f.geometry);
  }
}
const neighborhoods = {};
const missing = [];
for (const n of hoods.neighborhoods) {
  const g = hoodGeo.get(n.id) ?? hoodGeo.get(slug(n.label));
  if (g) neighborhoods[n.id] = featureCentroid(g);
  else missing.push(n.id);
}

const districts = {};
for (const f of readGeo('planning_districts').features) {
  districts[slug(f.properties.dist_name)] = featureCentroid(f.geometry);
}
const wanted = new Set(hoods.planning_districts.map((d) => (typeof d === 'string' ? d : d.id)));
for (const id of wanted) if (!districts[id]) missing.push(`district:${id}`);

const zips = {};
for (const f of readGeo('zipcodes').features) {
  zips[String(f.properties.code)] = featureCentroid(f.geometry);
}
// ZIP codes the vocabulary places without a map area get their planning district's middle.
for (const [zip, info] of Object.entries(hoods.zip_districts_unverified ?? {})) {
  if (!zips[zip] && districts[info.district]) zips[zip] = districts[info.district];
}

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)));
const fmt = (o) =>
  Object.entries(sorted(o))
    .map(([k, [lat, lng]]) => `  ${/^[a-z_]+$/.test(k) ? k : `'${k}'`}: [${lat}, ${lng}],`)
    .join('\n');

const text = `// GENERATED by scripts/make-centroids.mjs. Do not edit by hand.
//
// The middle of each Philadelphia neighborhood, planning district and ZIP code as [latitude,
// longitude]. Sources: OpenDataPhilly neighborhood boundaries (Creative Commons Attribution 4.0,
// Abaca Labs) and City of Philadelphia planning district and ZIP code boundaries (City of
// Philadelphia License). Used only to estimate travel time in the browser (engine/travel.ts).

export type LatLng = readonly [number, number];

export const NEIGHBORHOOD_CENTERS: Readonly<Record<string, LatLng>> = {
${fmt(neighborhoods)}
};

export const DISTRICT_CENTERS: Readonly<Record<string, LatLng>> = {
${fmt(districts)}
};

export const ZIP_CENTERS: Readonly<Record<string, LatLng>> = {
${fmt(zips)}
};
`;
fs.writeFileSync(outFile, text);
console.log(
  `wrote ${path.relative(process.cwd(), outFile)}: ${Object.keys(neighborhoods).length} neighborhoods, ${Object.keys(districts).length} districts, ${Object.keys(zips).length} ZIP codes`,
);
if (missing.length) console.log(`no boundary found for: ${missing.join(', ')}`);
